// scripts/openapi/collect.mjs
//
// Writes src/lib/openapi/contracts.generated.ts: a static import of every
// src/app/api/v1/**/route.contract.ts. The spec build, the /api/v1/openapi.json
// route and the coverage test all read contracts through it, because a route
// handler can't glob the filesystem at runtime. Sorted, so the output is
// deterministic and `check:openapi` can diff it.
//
// Also writes src/lib/openapi/schemas/enums.generated.ts: every Prisma enum as
// a plain string tuple, so contract schemas can name enum values without
// importing @prisma/client (contract files stay pure) and without hand-kept
// copies that drift.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = "src/app/api/v1";
const OUT = "src/lib/openapi/contracts.generated.ts";

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : e.name === "route.contract.ts" ? [p] : [];
  });
}

const files = walk(ROOT).map((f) => f.split(path.sep).join("/")).sort();
const lines = [
  "// GENERATED by scripts/openapi/collect.mjs. Do not edit; run `npm run openapi`.",
  "",
  ...files.map((f, i) => `import * as c${i} from "@/${f.replace(/^src\//, "").replace(/\.ts$/, "")}";`),
  "",
  `export const contractModules: readonly Record<string, unknown>[] = [${files.map((_, i) => `c${i}`).join(", ")}];`,
  "",
];
writeFileSync(OUT, lines.join("\n"));
console.log(`collect: ${files.length} contract file(s) -> ${OUT}`);

const ENUMS_OUT = "src/lib/openapi/schemas/enums.generated.ts";
const schema = readFileSync("prisma/schema.prisma", "utf8");
const enums = [...schema.matchAll(/^enum (\w+) \{([\s\S]*?)^\}/gm)].map(([, name, body]) => [
  name,
  body.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("//") && !l.startsWith("@"))
    .map((l) => l.split(/\s+/)[0]),
]);
writeFileSync(ENUMS_OUT, [
  "// GENERATED by scripts/openapi/collect.mjs from prisma/schema.prisma. Do not edit.",
  "",
  ...enums.map(([name, values]) => `export const ${name} = ${JSON.stringify(values)} as const;`),
  "",
].join("\n"));
console.log(`collect: ${enums.length} enum(s) -> ${ENUMS_OUT}`);
