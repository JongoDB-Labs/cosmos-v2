import { camelSlug } from "./slug.mjs";

/**
 * Render the two generated composition files that register composed plugins.
 *
 * Extracted from sync.mjs so the output can be asserted directly. It is the one
 * place in the toolchain that turns a plugin SLUG into a JavaScript IDENTIFIER,
 * and getting that wrong is not a soft failure: interpolating a kebab-case slug
 * raw emits `import { pi-planningManifest } …`, which is a syntax error that
 * takes the whole composed build down. That shipped undetected because every
 * slug in use was a single word.
 *
 * @typedef {{slug: string, importPath: string, serverPath: string, version?: string|null}} PluginEntry
 */

const GENERATED = "// GENERATED by scripts/plugins/sync.mjs — do not edit; not committed.";

/** Client-safe manifest composition (may enter the client bundle). */
export function renderRegistryIndex(entries) {
  return (
    entries.map((m) => `import { ${camelSlug(m.slug)}Manifest } from "${m.importPath}";`).join("\n") +
    `\nimport { PluginRegistry } from "../registry";\n\n${GENERATED}\n` +
    entries
      .map((m) =>
        // plugin.json wins over whatever the manifest hardcodes. See the note in
        // sync.mjs: a manifest version lagging plugin.json means onUpgrade silently
        // stops firing and the Plugins screen reports the old number, with no error
        // anywhere. Stamping it at composition removes the chance for every plugin,
        // composed now or later.
        m.version
          ? `PluginRegistry.register({ ...${camelSlug(m.slug)}Manifest, version: ${JSON.stringify(m.version)} });`
          : `PluginRegistry.register(${camelSlug(m.slug)}Manifest);`,
      )
      .join("\n") +
    "\nexport {};\n"
  );
}

/** Server-only hook composition (never bundled client-side). */
export function renderRegistryServer(entries) {
  return (
    `import "./index";\nimport { PluginServerRegistry } from "../registry";\nimport { IntegrationRegistry } from "@/lib/integrations/registry";\n` +
    entries.map((m) => `import { ${camelSlug(m.slug)}ServerHooks } from "${m.serverPath}";`).join("\n") +
    `\n\n${GENERATED}\n` +
    entries
      .map(
        (m) =>
          `PluginServerRegistry.register(${camelSlug(m.slug)}ServerHooks);\n` +
          `for (const p of ${camelSlug(m.slug)}ServerHooks.integrations ?? []) IntegrationRegistry.register(p);`,
      )
      .join("\n") +
    "\nexport {};\n"
  );
}
